-- ─────────────────────────────────────────────────────────────
-- 1. plans — subscription tiers shown on the pricing section
-- ─────────────────────────────────────────────────────────────
create table if not exists public.plans (
  id               bigint primary key generated by default as identity,
  name             text not null,
  price            numeric not null default 0,
  is_monthly       boolean not null default true,
  daily_limit      integer not null default 3,
  daily_chat_limit integer not null default 10,
  features         text[] default '{}',
  payment_link     text,
  price_id         text,
  created_at       timestamptz not null default now()
);

-- Plans are public catalogue data: anyone may read, nobody may write.
alter table public.plans enable row level security;
drop policy if exists "plans_public_read" on public.plans;
create policy "plans_public_read" on public.plans for select using (true);

